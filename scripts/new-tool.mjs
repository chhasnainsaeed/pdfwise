// Scaffolds a new tool: a working screen in src/tools/, its entry in src/tools.js and its icon.
// The tool then appears everywhere automatically: home grid, menus, Ctrl+K search, 3D scene,
// its own pre-rendered SEO page, the sitemap and llms.txt.
//
//   npm run new-tool                                    # asks for the details
//   npm run new-tool -- "Grayscale PDF" --category edit --kind pdf --icon Contrast --multiple
//
// Options: --category (see CATEGORIES in src/tools.js), --kind (pdf | image | any — see KINDS in
// src/lib/files.js), --icon (a lucide-react icon name, https://lucide.dev/icons), --multiple,
// --color '#hex', --description '…'. --dry-run prints what would change without writing.

import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import path from 'node:path'
import { createInterface } from 'node:readline/promises'
import { fileURLToPath } from 'node:url'

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..')
const rel = (p) => path.join(root, p)
const { CATEGORIES, TOOLS } = await import(rel('src/tools.js'))
const { LANDING_PAGES } = await import(rel('src/landing.js'))
const lucide = await import('lucide-react')

// --- Arguments ---
const args = process.argv.slice(2)
const flags = {}
const positional = []
for (let i = 0; i < args.length; i++) {
  if (args[i].startsWith('--')) {
    const key = args[i].slice(2)
    const next = args[i + 1]
    if (next === undefined || next.startsWith('--')) flags[key] = true
    else flags[key] = args[++i]
  } else positional.push(args[i])
}

const rl = process.stdin.isTTY ? createInterface({ input: process.stdin, output: process.stdout }) : null
async function ask(question, fallback) {
  if (!rl) return fallback
  const answer = (await rl.question(`${question}${fallback ? ` (${fallback})` : ''}: `)).trim()
  return answer || fallback
}
const fail = (msg) => {
  rl?.close()
  console.error(`\n✗ ${msg}`)
  process.exit(1)
}

const name = positional[0] || (await ask('Tool name, e.g. “Grayscale PDF”'))
if (!name) fail('Give the tool a name: npm run new-tool -- "Grayscale PDF"')
const id = name
  .toLowerCase()
  .replace(/[^a-z0-9]+/g, '-')
  .replace(/^-|-$/g, '')
const component = name
  .replace(/[^A-Za-z0-9]+/g, ' ')
  .trim()
  .split(/\s+/)
  .map((w) => w[0].toUpperCase() + w.slice(1))
  .join('')
const categoryIds = CATEGORIES.map((c) => c.id)
const category = flags.category || (await ask(`Category [${categoryIds.join(', ')}]`, 'edit'))
const kind = flags.kind || (await ask('Accepts [pdf, image, any]', 'pdf'))
const icon = flags.icon || (await ask('lucide-react icon name (https://lucide.dev/icons)', 'FileText'))
const description =
  flags.description || (await ask('One-sentence description', `${name} — describe what it does in one sentence.`))
const multiple = Boolean(flags.multiple)
const color = flags.color || '#5b6cff'
rl?.close()

// --- Checks ---
if (!id || !/^[A-Z]/.test(component)) fail(`“${name}” doesn't make a usable id. Use letters and numbers.`)
if (TOOLS.some((t) => t.id === id)) fail(`A tool with id “${id}” already exists.`)
if (LANDING_PAGES.some((p) => p.slug === id)) fail(`“/${id}” is already a landing page in src/landing.js.`)
if (existsSync(rel(`src/tools/${component}.jsx`))) fail(`src/tools/${component}.jsx already exists.`)
if (!categoryIds.includes(category))
  fail(`Unknown category “${category}”. Use one of: ${categoryIds.join(', ')} (or add one to CATEGORIES).`)
if (!['pdf', 'image', 'any'].includes(kind))
  fail(`Unknown kind “${kind}”. Use pdf, image or any (Office kinds need the server).`)
if (!/^#[0-9a-f]{6}$/i.test(color)) fail(`--color must look like #5b6cff.`)
if (typeof lucide[icon] !== 'object' && typeof lucide[icon] !== 'function')
  fail(`“${icon}” isn't a lucide-react icon. Browse https://lucide.dev/icons and use the PascalCase name.`)

// --- The tool's registry entry ---
const q = (s) => `'${String(s).replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
const entry = `  {
    id: ${q(id)},
    name: ${q(name)},
    category: ${q(category)},
    color: ${q(color)},
    icon: ${q(icon)},
    component: ${q(component)},
    kind: ${q(kind)},
    multiple: ${multiple},
    badge: 'New',
    description: ${q(description)},
    action: ${q(name)},
    processing: 'Working on your files…',
    done: 'Your files are ready',
    related: ['compress-pdf', 'merge-pdf'],
    keywords: [],
  },
`

// --- A working screen to start from ---
const screen = `import FileCard from '../components/FileCard.jsx'
import ToolLayout from '../components/ToolLayout.jsx'
import { PDF_TYPE, baseName } from '../lib/files.js'
import { useSession } from '../lib/hooks.js'
${kind === 'pdf' ? "import { loadPdf } from '../lib/ops.js'\nimport { usePdfInfo } from '../lib/pdfjs.js'\n" : ''}
/**
 * ${name}: ${description}
 *
 * Generated by \`npm run new-tool\`. Replace processFile() with the real work; run() shows
 * progress and the download screen, and zips several results automatically.
 */
async function processFile(file) {
${
  kind === 'pdf'
    ? `  const pdf = await loadPdf(file)
  // TODO: change the document here, e.g. pdf.getPages().forEach((page) => …)
  return pdf.save()`
    : `  // TODO: turn \`file\` into the output bytes (a Uint8Array or Blob).
  return file`
}
}

export default function ${component}() {
  const { files, setFiles, run } = useSession()
${kind === 'pdf' ? '  const info = usePdfInfo(files)\n' : '  const info = {}\n'}
  const go = () =>
    run(async ({ progress }) => {
      const out = []
      for (let i = 0; i < files.length; i++) {
        const { file } = files[i]
        out.push({ name: \`\${baseName(file.name)}-${id}.pdf\`, type: PDF_TYPE, data: await processFile(file) })
        progress(i + 1, files.length)
      }
      return { files: out, zipName: '${id}.zip' }
    })

  return (
    <ToolLayout
      main={
        <div className="file-grid">
          {files.map((item) => (
            <FileCard
              key={item.id}
              item={item}
              info={info[item.id]}
              onRemove={() => setFiles((list) => list.filter((f) => f.id !== item.id))}
            />
          ))}
        </div>
      }
      sidebar={<p className="side-text">TODO: options for ${name.replace(/[{}]/g, '')} go here.</p>}
      onAction={go}
    />
  )
}
`

// --- Apply ---
const toolsPath = rel('src/tools.js')
const toolsSrc = readFileSync(toolsPath, 'utf8')
const end = toolsSrc.indexOf('\n]\n\nexport const TOOLS_BY_ID')
if (end < 0) fail('Couldn’t find the end of the TOOLS list in src/tools.js.')
const nextTools = `${toolsSrc.slice(0, end + 1)}${entry}${toolsSrc.slice(end + 1)}`

const iconsPath = rel('src/components/icons.js')
let iconsSrc = readFileSync(iconsPath, 'utf8')
const iconListed = new RegExp(`^  ${icon},$`, 'm').test(iconsSrc)
if (!iconListed) {
  const names = [...iconsSrc.matchAll(/^ {2}(\w+),$/gm)].map((m) => m[1])
  const all = [...new Set([...names, icon])].sort()
  iconsSrc = iconsSrc
    .replace(
      /import \{\n[\s\S]*?\n\} from 'lucide-react'/,
      `import {\n${all.map((n) => `  ${n},`).join('\n')}\n} from 'lucide-react'`,
    )
    .replace(
      /export const ICONS = \{\n[\s\S]*?\n\}/,
      `export const ICONS = {\n${all.map((n) => `  ${n},`).join('\n')}\n}`,
    )
}

if (flags['dry-run']) {
  console.log(`Would add src/tools/${component}.jsx and this entry to src/tools.js:\n\n${entry}`)
  if (!iconListed) console.log(`Would add ${icon} to src/components/icons.js`)
  process.exit(0)
}
writeFileSync(rel(`src/tools/${component}.jsx`), screen)
writeFileSync(toolsPath, nextTools)
if (!iconListed) writeFileSync(iconsPath, iconsSrc)

console.log(`
✓ Created ${name} → /${id}
  src/tools/${component}.jsx    the screen (edit processFile and the sidebar)
  src/tools.js                  its entry: description, action, related, keywords, faq…
${iconListed ? '' : `  src/components/icons.js       added the ${icon} icon\n`}
Next:
  1. npm run dev, then open http://localhost:5173/${id}
  2. Fill in the TODOs, and write keywords people search for in its entry.
  3. npm test, which checks the registry, SEO titles and presets.
`)
